export const millionCities = russianCities;
export type MillionCity = (typeof russianCities)[number];

function normalizeCity(value: string): string {
  return value.trim().toLocaleLowerCase("ru-RU");
}

export function filterCities(query: string, limit = 8): string[] {
  const q = normalizeCity(query);
  if (!q) return [...russianCities].slice(0, limit);
  const starts: string[] = [];
  const includes: string[] = [];
  for (const city of russianCities) {
    const name = normalizeCity(city);
    if (name.startsWith(q)) starts.push(city);
    else if (name.includes(q)) includes.push(city);
    if (starts.length >= limit) break;
  }
  return [...starts, ...includes].slice(0, limit);
}

/** First city whose name starts with the typed prefix. */
export function completeCity(query: string): string | null {
  const q = normalizeCity(query);
  if (!q) return null;
  return (
    russianCities.find((city) => normalizeCity(city).startsWith(q)) ?? null
  );
}
