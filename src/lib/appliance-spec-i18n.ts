function normalizeKey(text: string): string {
  return text.trim().toLowerCase().replace(/\s+/g, " ");
}

export function translateApplianceSpecLabel(label: string): string {
  const key = normalizeKey(label);
  return LABEL_RU[key] ?? label;
}

export function translateApplianceSpecValue(value: string): string {
  const trimmed = value.trim();
  const key = normalizeKey(trimmed);
  return VALUE_RU[key] ?? trimmed;
}

/** Localize Icecat specs — no-op for labels already in Russian. */
export function localizeApplianceSpecs(specs: ApplianceSpec[]): ApplianceSpec[] {
  return specs.map((spec) => ({
    label: translateApplianceSpecLabel(spec.label),
    value: translateApplianceSpecValue(spec.value),
  }));
}
